"""Plain data containers shared across the UI and services."""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class CheckinData:
    """What the user submitted. Contains no names, phone numbers or identifiers."""

    mood: str
    concern_category: str
    duration: str
    impact: str
    description: str


@dataclass
class Resource:
    title: str
    type: str
    description: str


@dataclass
class AnalysisResult:
    """Structured result displayed on the recommendations page.

    ``mode`` is one of:
      - ``"ai"``        - generated by the configured AI model (Groq)
      - ``"fallback"``  - built-in guidance (API unavailable / not configured)
      - ``"crisis"``    - safety layer triggered; no ordinary recommendations
    """

    mode: str
    concern_category: str = ""
    concern_summary: str = ""
    recommended_resources: list[Resource] = field(default_factory=list)
    practical_next_steps: list[str] = field(default_factory=list)
    counselling_level: str = "optional"
    counselling_reason: str = ""
    urgency_level: str = "low"
    supportive_message: str = ""
    # Context for display only (no free text is retained after analysis)
    mood: str = ""
    duration: str = ""
    impact: str = ""
    fallback_reason: str = ""  # short, user-friendly reason when mode == "fallback"
    safety_category: str = ""  # set when mode == "crisis"
